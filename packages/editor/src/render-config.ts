/**
 * Render the configuration key tables for Neovim and Vim.
 *
 * The declaration is the single source. Both tables carry the same rows in the
 * same order: the dotted name, the Vim variable, the container flag, the value
 * type, the closed enumeration, the default or sentinel, the baseline alias,
 * the value class, and the one shared error format.
 *
 * This module is pure: it returns data and writes nothing. The write-only
 * entrypoint is `scripts/generate-config-tables.ts`.
 */
import { CONFIG_ERROR_FORMAT, configKeys, type ConfigKey } from "@mdv/core/config";

const HEADER = "Generated by scripts/generate-config-tables.ts. Do not edit.";

type DefaultKind = "nil" | "object" | "list" | "value";

export type ConfigRow = {
  readonly name: string;
  readonly vimName: string;
  readonly container: boolean;
  readonly type: ConfigKey["type"];
  readonly values: readonly string[];
  readonly defaultKind: DefaultKind;
  readonly default: unknown;
  readonly alias: string | null;
  readonly aliasScope: ConfigKey["aliasScope"];
  readonly inverted: boolean;
  readonly class: ConfigKey["class"];
};

export type RenderedConfig = {
  readonly errorFormat: string;
  readonly rows: readonly ConfigRow[];
  readonly nvim: { readonly file: string; readonly source: string };
  readonly vim: { readonly file: string; readonly source: string };
};

const defaultKindOf = (value: unknown): DefaultKind => {
  if (value === null || value === undefined) return "nil";
  if (Array.isArray(value)) return "list";
  if (typeof value === "object") return "object";
  return "value";
};

const rowOf = (key: ConfigKey): ConfigRow => ({
  name: key.name,
  vimName: key.vimName,
  container: key.container,
  type: key.type,
  values: key.values,
  defaultKind: defaultKindOf(key.default),
  default: key.container ? null : key.default,
  alias: key.alias,
  aliasScope: key.aliasScope,
  inverted: key.inverted,
  class: key.class,
});

const rows = (): readonly ConfigRow[] => configKeys().map(rowOf);

const luaValue = (value: unknown): string => {
  if (value === null || value === undefined) return "nil";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  if (Array.isArray(value))
    return value.length === 0 ? "{}" : `{ ${value.map(luaValue).join(", ")} }`;
  if (typeof value === "object") {
    if (Object.keys(value).length === 0) return "{}";
  }
  throw new Error("unsupported Lua default");
};

const luaRow = (row: ConfigRow): string =>
  `  { ${[
    `name = ${JSON.stringify(row.name)}`,
    `vim_name = ${JSON.stringify(row.vimName)}`,
    `container = ${row.container}`,
    `type = ${JSON.stringify(row.type)}`,
    `values = ${luaValue(row.values)}`,
    `default = ${luaValue(row.default)}`,
    `default_kind = ${JSON.stringify(row.defaultKind)}`,
    `alias = ${luaValue(row.alias)}`,
    `alias_scope = ${luaValue(row.aliasScope)}`,
    `inverted = ${row.inverted}`,
    `class = ${luaValue(row.class)}`,
  ].join(", ")} }`;

const luaConfig = (table: readonly ConfigRow[]): string =>
  [
    `-- ${HEADER}`,
    "local M = {}",
    "",
    `M.error_format = ${JSON.stringify(CONFIG_ERROR_FORMAT)}`,
    "",
    "M.keys = {",
    table.map(luaRow).join(",\n"),
    "}",
    "",
    "return M",
    "",
  ].join("\n");

const vimString = (value: string): string => `'${value.replaceAll("'", "''")}'`;

const vimValue = (value: unknown): string => {
  if (value === null || value === undefined) return "v:null";
  if (typeof value === "string") return vimString(value);
  if (typeof value === "boolean") return value ? "v:true" : "v:false";
  if (typeof value === "number") return String(value);
  if (Array.isArray(value)) return `[${value.map(vimValue).join(", ")}]`;
  if (typeof value === "object") {
    if (Object.keys(value).length === 0) return "{}";
  }
  throw new Error("unsupported Vimscript default");
};

const vimRow = (row: ConfigRow): string =>
  `{ ${[
    `'name': ${vimString(row.name)}`,
    `'vim_name': ${vimString(row.vimName)}`,
    `'container': ${vimValue(row.container)}`,
    `'type': ${vimString(row.type)}`,
    `'values': ${vimValue(row.values)}`,
    `'default': ${vimValue(row.default)}`,
    `'default_kind': ${vimString(row.defaultKind)}`,
    `'alias': ${vimValue(row.alias)}`,
    `'alias_scope': ${vimValue(row.aliasScope)}`,
    `'inverted': ${vimValue(row.inverted)}`,
    `'class': ${vimValue(row.class)}`,
  ].join(", ")} }`;

const vimConfig = (table: readonly ConfigRow[]): string =>
  [
    `" ${HEADER}`,
    `let s:config = {'error_format': ${vimString(CONFIG_ERROR_FORMAT)}, 'keys': [`,
    table.map((row) => `      \\ ${vimRow(row)}`).join(",\n"),
    "      \\ ]}",
    "",
    "function! markdown_viewer#generated#config#get() abort",
    "  return s:config",
    "endfunction",
    "",
  ].join("\n");

export const renderConfig = (): RenderedConfig => {
  const table = rows();

  return {
    errorFormat: CONFIG_ERROR_FORMAT,
    rows: table,
    nvim: {
      file: "nvim/lua/markdown_viewer/generated/config.lua",
      source: luaConfig(table),
    },
    vim: {
      file: "vim/autoload/markdown_viewer/generated/config.vim",
      source: vimConfig(table),
    },
  };
};
