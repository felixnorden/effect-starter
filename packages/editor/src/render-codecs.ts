const fieldsByTag = Object.fromEntries(
  schemaMessages.map((message) => [message.tag, message.fields.map((field) => field.name)]),
);
const optionalByTag = Object.fromEntries(
  schemaMessages.map((message) => [
    message.tag,
    message.fields.filter((field) => field.optional).map((field) => field.name),
  ]),
);

const manifest = {
  editorProtocolVersion: EDITOR_PROTOCOL_VERSION,
  maxFrameBytes: MAX_FRAME_BYTES,
  frameTerminator: FRAME_TERMINATOR,
  tags: schemaMessages.map((message) => message.tag),
  stages,
  fields: fieldsByTag,
  optionalFields: optionalByTag,
  cases: cases.map((entry) => ({
    name: entry.name,
    file: entry.file,
    tag: entry.tag,
    message: entry.message,
  })),
  versionMismatch: {
    file: "version-mismatch.frame",
    clientVersion: EDITOR_PROTOCOL_VERSION + 1,
    serverVersion: EDITOR_PROTOCOL_VERSION,
    message: "editor protocol version mismatch",
  },
};

/** Sort object keys so the manifest is byte-stable. */
const canonical = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(canonical);
  if (value !== null && typeof value === "object") {
    const source = value as Record<string, unknown>;
    return Object.fromEntries(
      Object.keys(source)
        .sort()
        .map((key) => [key, canonical(source[key])]),
    );
  }
  return value;
};

const json = (value: unknown): string => `${JSON.stringify(canonical(value), null, 2)}\n`;

const luaString = (value: string): string => JSON.stringify(value);

const luaList = (values: readonly string[]): string =>
  values.length === 0 ? "{}" : `{ ${values.map(luaString).join(", ")} }`;

const luaFieldTypes = (message: Message): string =>
  message.fields.map((field) => `    ${field.name} = ${luaString(field.kind)},`).join("\n");

const luaFieldValues = (message: Message): string => {
  const entries = message.fields
    .filter((field) => field.values.length > 0)
    .map((field) => `    ${field.name} = ${luaList(field.values)},`);
  return entries.length === 0 ? "" : entries.join("\n");
};

const luaWire = (): string =>
  [
    `-- ${HEADER}`,
    "local M = {}",
    "",
    `M.editor_protocol_version = ${EDITOR_PROTOCOL_VERSION}`,
    `M.max_frame_bytes = ${MAX_FRAME_BYTES}`,
    `M.frame_terminator = ${FRAME_TERMINATOR}`,
    "",
    `M.tags = ${luaList(schemaMessages.map((message) => message.tag))}`,
    `M.stages = ${luaList(stages)}`,
    "",
    "M.messages = {",
    schemaMessages
      .map((message) =>
        [
          `  ${message.tag} = {`,
          `    required = ${luaList(
            message.fields.filter((field) => !field.optional).map((field) => field.name),
          )},`,
          `    optional = ${luaList(
            message.fields.filter((field) => field.optional).map((field) => field.name),
          )},`,
          "  },",
        ].join("\n"),
      )
      .join("\n"),
    "}",
    "",
    "M.field_types = {",
    schemaMessages
      .map((message) => [`  ${message.tag} = {`, luaFieldTypes(message), "  },"].join("\n"))
      .join("\n"),
    "}",
    "",
    "M.field_values = {",
    schemaMessages
      .map((message) => {
        const values = luaFieldValues(message);
        return values === "" ? "" : [`  ${message.tag} = {`, values, "  },"].join("\n");
      })
      .filter((entry) => entry !== "")
      .join("\n"),
    "}",
    "",
    "return M",
    "",
  ].join("\n");

const luaCodecSource = (): string => `-- ${HEADER}
local wire = require("markdown_viewer.generated.wire")

local M = {}

M.editor_protocol_version = wire.editor_protocol_version
M.max_frame_bytes = wire.max_frame_bytes
M.frame_terminator = wire.frame_terminator
M.tags = wire.tags
M.stages = wire.stages

local function encode_json(value)
  return vim.json.encode(value)
end

local function decode_json(text)
  local ok, value = pcall(vim.json.decode, text)
  if not ok then
    return nil
  end
  return value
end

local function invalid(tag, name, detail)
  return {
    _tag = "invalid",
    fault = "protocol",
    detail = "editor frame " .. tag .. "." .. name .. ": " .. detail,
  }
end

local function matches_type(value, kind, values)
  if kind == "string" then
    return type(value) == "string"
  end
  if kind == "number" then
    return type(value) == "number"
  end
  if kind == "literals" then
    for _, allowed in ipairs(values) do
      if value == allowed then
        return true
      end
    end
    return false
  end
  if kind == "json" then
    return value ~= nil
  end
  return false
end

function M.encode_message(message)
  local tag = message._tag
  local spec = wire.messages[tag]
  if spec == nil then
    error("unknown editor message tag: " .. tostring(tag))
  end
  local payload = {}
  for _, name in ipairs(spec.required) do
    payload[name] = message[name]
  end
  for _, name in ipairs(spec.optional) do
    if message[name] ~= nil then
      payload[name] = message[name]
    end
  end
  return encode_json(payload)
end

function M.encode_frame(message)
  return M.encode_message(message) .. string.char(wire.frame_terminator)
end

function M.decode_frame(line)
  if type(line) ~= "string" then
    return nil, { _tag = "invalid", fault = "protocol", detail = "editor frame is not a string" }
  end
  local payload_text = line
  if payload_text:sub(-2) == "\\r\\n" then
    payload_text = payload_text:sub(1, -3)
  elseif payload_text:sub(-1) == "\\n" then
    payload_text = payload_text:sub(1, -2)
  end
  if #payload_text > wire.max_frame_bytes then
    return nil, {
      _tag = "fatal",
      fault = "cap",
      detail = "editor frame exceeds the " .. tostring(wire.max_frame_bytes) .. "-byte cap",
    }
  end
  if payload_text == "" then
    return nil, { _tag = "invalid", fault = "protocol", detail = "editor frame is empty" }
  end
  local payload = decode_json(payload_text)
  if type(payload) ~= "table" then
    return nil, { _tag = "invalid", fault = "protocol", detail = "editor frame is not JSON" }
  end
  local version = payload.editorProtocolVersion
  if version ~= wire.editor_protocol_version then
    return nil, {
      _tag = "mismatch",
      fault = "version",
      detail = "editor protocol version mismatch: client "
        .. tostring(version)
        .. ", server "
        .. tostring(wire.editor_protocol_version),
      clientVersion = type(version) == "number" and version or nil,
      serverVersion = wire.editor_protocol_version,
    }
  end
  local spec = wire.messages[payload._tag]
  if spec == nil then
    return nil, { _tag = "invalid", fault = "protocol", detail = "editor frame has an unknown tag" }
  end
  local types = wire.field_types[payload._tag] or {}
  local values = wire.field_values[payload._tag] or {}
  for _, name in ipairs(spec.required) do
    if payload[name] == nil then
      return nil, invalid(payload._tag, name, "missing")
    end
    if not matches_type(payload[name], types[name], values[name]) then
      return nil, invalid(payload._tag, name, "wrong type")
    end
  end
  for _, name in ipairs(spec.optional) do
    if payload[name] ~= nil and not matches_type(payload[name], types[name], values[name]) then
      return nil, invalid(payload._tag, name, "wrong type")
    end
  end
  return payload
end

return M
`;

const vimString = (value: string): string => `'${value.replaceAll("'", "''")}'`;

const vimValue = (value: unknown): string => {
  if (Array.isArray(value)) return `[${value.map(vimValue).join(", ")}]`;
  if (value !== null && typeof value === "object") {
    const source = value as Record<string, unknown>;
    const entries = Object.keys(source).map((key) => `${vimString(key)}: ${vimValue(source[key])}`);
    return entries.length === 0 ? "{}" : `{${entries.join(", ")}}`;
  }
  if (typeof value === "string") return vimString(value);
  if (typeof value === "number") return String(value);
  throw new Error(`unsupported Vimscript value: ${String(value)}`);
};

const vimWire = (): string => {
  const wire = {
    editor_protocol_version: EDITOR_PROTOCOL_VERSION,
    max_frame_bytes: MAX_FRAME_BYTES,
    frame_terminator: FRAME_TERMINATOR,
    tags: schemaMessages.map((message) => message.tag),
    stages,
    messages: Object.fromEntries(
      schemaMessages.map((message) => [
        message.tag,
        {
          required: message.fields.filter((field) => !field.optional).map((field) => field.name),
          optional: message.fields.filter((field) => field.optional).map((field) => field.name),
        },
      ]),
    ),
    field_types: Object.fromEntries(
      schemaMessages.map((message) => [
        message.tag,
        Object.fromEntries(message.fields.map((field) => [field.name, field.kind])),
      ]),
    ),
    field_values: Object.fromEntries(
      schemaMessages
        .filter((message) => message.fields.some((field) => field.values.length > 0))
        .map((message) => [
          message.tag,
          Object.fromEntries(
            message.fields
              .filter((field) => field.values.length > 0)
              .map((field) => [field.name, field.values]),
          ),
        ]),
    ),
  };

  return [
    `" ${HEADER}`,
    `let s:wire = ${vimValue(wire)}`,
    "",
    "function! markdown_viewer#generated#wire#get() abort",
    "  return s:wire",
    "endfunction",
    "",
  ].join("\n");
};

const vimCodecSource = (): string => `" ${HEADER}
let s:wire = markdown_viewer#generated#wire#get()

function! markdown_viewer#generated#codec#version() abort
  return s:wire.editor_protocol_version
endfunction

function! s:Invalid(fault, detail) abort
  return {'_tag': 'invalid', 'fault': a:fault, 'detail': a:detail}
endfunction

function! s:Matches(value, kind, values) abort
  if a:kind ==# 'string'
    return type(a:value) == v:t_string
  elseif a:kind ==# 'number'
    return type(a:value) == v:t_number || type(a:value) == v:t_float
  elseif a:kind ==# 'literals'
    return index(a:values, a:value) >= 0
  elseif a:kind ==# 'json'
    return type(a:value) != v:t_none
  endif
  return 0
endfunction

function! markdown_viewer#generated#codec#encode_message(message) abort
  let l:tag = get(a:message, '_tag', '')
  let l:spec = get(s:wire.messages, l:tag, {})
  if empty(l:spec)
    throw 'markdown_viewer: unknown editor message tag ' . string(l:tag)
  endif
  let l:payload = {}
  for l:name in l:spec.required
    let l:payload[l:name] = a:message[l:name]
  endfor
  for l:name in l:spec.optional
    if has_key(a:message, l:name)
      let l:payload[l:name] = a:message[l:name]
    endif
  endfor
  return json_encode(l:payload)
endfunction

function! markdown_viewer#generated#codec#encode_frame(message) abort
  return markdown_viewer#generated#codec#encode_message(a:message) . nr2char(s:wire.frame_terminator)
endfunction

function! markdown_viewer#generated#codec#decode_frame(line) abort
  if type(a:line) != v:t_string
    return [0, s:Invalid('protocol', 'editor frame is not a string')]
  endif
  let l:text = a:line
  if l:text[-2:] ==# "\\r\\n"
    let l:text = l:text[: -3]
  elseif l:text[-1:] ==# "\\n"
    let l:text = l:text[: -2]
  endif
  if strlen(l:text) > s:wire.max_frame_bytes
    return [0, {'_tag': 'fatal', 'fault': 'cap',
          \\ 'detail': 'editor frame exceeds the ' . s:wire.max_frame_bytes . '-byte cap'}]
  endif
  if l:text ==# ''
    return [0, s:Invalid('protocol', 'editor frame is empty')]
  endif
  try
    let l:payload = json_decode(l:text)
  catch
    return [0, s:Invalid('protocol', 'editor frame is not JSON')]
  endtry
  if type(l:payload) != v:t_dict
    return [0, s:Invalid('protocol', 'editor frame is not JSON')]
  endif
  let l:version = get(l:payload, 'editorProtocolVersion', -1)
  if l:version != s:wire.editor_protocol_version
    let l:error = {'_tag': 'mismatch', 'fault': 'version',
          \\ 'detail': 'editor protocol version mismatch: client ' . string(l:version) .
          \\ ', server ' . string(s:wire.editor_protocol_version),
          \\ 'serverVersion': s:wire.editor_protocol_version}
    if type(l:version) == v:t_number
      let l:error.clientVersion = l:version
    endif
    return [0, l:error]
  endif
  let l:tag = get(l:payload, '_tag', '')
  let l:spec = get(s:wire.messages, l:tag, {})
  if empty(l:spec)
    return [0, s:Invalid('protocol', 'editor frame has an unknown tag')]
  endif
  let l:types = get(s:wire.field_types, l:tag, {})
  let l:values = get(s:wire.field_values, l:tag, {})
  for l:name in l:spec.required
    if !has_key(l:payload, l:name)
      return [0, s:Invalid('protocol', 'editor frame ' . l:tag . '.' . l:name . ': missing')]
    endif
    if !s:Matches(l:payload[l:name], get(l:types, l:name, ''), get(l:values, l:name, []))
      return [0, s:Invalid('protocol', 'editor frame ' . l:tag . '.' . l:name . ': wrong type')]
    endif
  endfor
  for l:name in l:spec.optional
    if has_key(l:payload, l:name)
      if !s:Matches(l:payload[l:name], get(l:types, l:name, ''), get(l:values, l:name, []))
        return [0, s:Invalid('protocol', 'editor frame ' . l:tag . '.' . l:name . ': wrong type')]
      endif
    endif
  endfor
  return [1, l:payload]
endfunction
`;

export type RenderedEditorWire = {
  readonly frames: readonly { readonly file: string; readonly bytes: Uint8Array }[];
  readonly manifest: string;
  readonly nvim: { readonly wire: string; readonly codec: string };
  readonly vim: { readonly wire: string; readonly codec: string };
};

export const render = (): RenderedEditorWire => ({
  frames: [
    ...cases.map((entry) => ({ file: entry.file, bytes: encodeFrame(entry.message) })),
    { file: "version-mismatch.frame", bytes: encodeFrame(versionMismatchMessage) },
  ],
  manifest: json(manifest),
  nvim: { wire: luaWire(), codec: luaCodecSource() },
  vim: { wire: vimWire(), codec: vimCodecSource() },
});
