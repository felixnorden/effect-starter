/**
 * Render the editor wire: one golden frame per case, the case manifest, and the
 * same codec for Neovim and Vim.
 *
 * The schemas are the single source. Tags, field names, field types, the stage
 * set, the version constant, and the frame cap are read from the schema AST, so
 * a schema edit that is not regenerated fails the gate. Output is deterministic:
 * LF endings, sorted keys, a fixed header, no timestamps.
 *
 * This module is pure: it returns data and writes nothing. The write-only
 * entrypoint is `scripts/generate-editor-frames.ts`.
 */
import { SchemaAST } from "effect";
import { encodeFrame, FRAME_TERMINATOR, MAX_FRAME_BYTES } from "@mdv/core/editor-frame";
import {
  EDITOR_PROTOCOL_VERSION,
  EditorMessageSchema,
  type EditorMessage,
} from "@mdv/core/editor-protocol";

const HEADER = "Generated by scripts/generate-editor-frames.ts. Do not edit.";

type FieldKind = "string" | "number" | "literals" | "json";

type Field = {
  readonly name: string;
  readonly kind: FieldKind;
  readonly optional: boolean;
  readonly values: readonly string[];
};

type Message = {
  readonly tag: string;
  readonly fields: readonly Field[];
};

const literalOf = (ast: SchemaAST.AST): string => {
  if (!SchemaAST.isLiteral(ast)) throw new Error("expected a literal AST");
  return String(ast.literal);
};

const kindOf = (
  ast: SchemaAST.AST,
): { readonly kind: FieldKind; readonly values: readonly string[] } => {
  if (SchemaAST.isString(ast)) return { kind: "string", values: [] };
  if (SchemaAST.isNumber(ast)) return { kind: "number", values: [] };
  if (SchemaAST.isLiteral(ast)) return { kind: "string", values: [] };
  if (SchemaAST.isUnknown(ast)) return { kind: "json", values: [] };
  if (SchemaAST.isUnion(ast)) {
    return { kind: "literals", values: ast.types.map((member) => literalOf(member)) };
  }
  throw new Error(`unsupported editor field AST: ${ast._tag}`);
};

const messages = (): readonly Message[] => {
  const ast = EditorMessageSchema.ast;
  if (!SchemaAST.isUnion(ast)) throw new Error("expected a union schema");

  return ast.types.map((member) => {
    if (!SchemaAST.isObjects(member)) throw new Error("expected an object member");
    const tagField = member.propertySignatures.find((property) => property.name === "_tag");
    if (tagField === undefined) throw new Error("message member has no _tag");

    return {
      tag: literalOf(tagField.type),
      fields: member.propertySignatures.map((property) => ({
        name: String(property.name),
        optional: property.type.context?.isOptional === true,
        ...kindOf(property.type),
      })),
    };
  });
};

const schemaMessages = messages();
const stageMessage = schemaMessages.find((message) => message.tag === "error");
const stages = stageMessage?.fields.find((field) => field.name === "stage")?.values ?? [];

if (stages.length === 0) throw new Error("the error schema has no stage set");

